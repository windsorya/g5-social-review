  // #3010：做不了的計畫題（查不到、考不到、停出未做）一樣不算「還要做」，列為 missingIds（不用做）；計畫本身照舊不刪
  function liveRemaining(s, bank, d) { return remainingOf(d).filter(function (id) { return servable(s, bank, id); }); }
